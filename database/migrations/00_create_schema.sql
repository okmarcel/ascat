-- Initial schema for an empty PostgreSQL database.
BEGIN;

CREATE TABLE users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT users_pkey PRIMARY KEY,
    username varchar(50) NOT NULL,
    email varchar(100) NOT NULL,
    password_hash text NOT NULL,
    role varchar(10) NOT NULL DEFAULT 'user',
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT users_username_check CHECK (username <> '' AND username !~ '[[:space:]]'),
    CONSTRAINT users_email_check CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+$'),
    CONSTRAINT users_password_hash_check CHECK (password_hash ~ '[^[:space:]]'),
    CONSTRAINT users_role_check CHECK (role IN ('user', 'admin'))
);

CREATE UNIQUE INDEX users_username_ci_uidx ON users (lower(username));
CREATE UNIQUE INDEX users_email_ci_uidx ON users (lower(email));

CREATE TABLE samples (
    sample_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT samples_pkey PRIMARY KEY,
    owner_id integer NOT NULL,
    name varchar(100) NOT NULL,
    length_seconds numeric(12,6) NOT NULL,
    bpm integer,
    file_format varchar(10) NOT NULL,
    upload_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    storage_key text NOT NULL,
    is_deleted boolean NOT NULL DEFAULT false,
    CONSTRAINT samples_owner_fkey FOREIGN KEY (owner_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT samples_name_check CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT samples_length_check CHECK (length_seconds > 0 AND length_seconds < 'Infinity'::numeric),
    CONSTRAINT samples_bpm_check CHECK (bpm BETWEEN 50 AND 300),
    CONSTRAINT samples_format_check CHECK (file_format IN ('wav', 'mp3', 'flac', 'ogg')),
    CONSTRAINT samples_upload_date_check CHECK (isfinite(upload_date)),
    CONSTRAINT samples_storage_key_check CHECK (storage_key ~ '[^[:space:]]'),
    CONSTRAINT samples_storage_key_key UNIQUE (storage_key)
);

CREATE TABLE tags (
    tag_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT tags_pkey PRIMARY KEY,
    name varchar(50) NOT NULL,
    CONSTRAINT tags_name_check CHECK (name ~ '[^[:space:]]' AND name = btrim(name))
);

CREATE UNIQUE INDEX tags_name_ci_uidx ON tags (lower(name));

CREATE TABLE sample_tags (
    sample_id integer NOT NULL,
    tag_id integer NOT NULL,
    CONSTRAINT sample_tags_pkey PRIMARY KEY (sample_id, tag_id),
    CONSTRAINT sample_tags_sample_fkey FOREIGN KEY (sample_id) REFERENCES samples (sample_id) ON DELETE CASCADE,
    CONSTRAINT sample_tags_tag_fkey FOREIGN KEY (tag_id) REFERENCES tags (tag_id) ON DELETE CASCADE
);

CREATE TABLE collections (
    collection_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT collections_pkey PRIMARY KEY,
    owner_id integer NOT NULL,
    name varchar(100) NOT NULL,
    CONSTRAINT collections_owner_fkey FOREIGN KEY (owner_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT collections_name_check CHECK (name ~ '[^[:space:]]')
);

CREATE TABLE collection_samples (
    collection_id integer NOT NULL,
    sample_id integer NOT NULL,
    CONSTRAINT collection_samples_pkey PRIMARY KEY (collection_id, sample_id),
    CONSTRAINT collection_samples_collection_fkey FOREIGN KEY (collection_id) REFERENCES collections (collection_id) ON DELETE CASCADE,
    CONSTRAINT collection_samples_sample_fkey FOREIGN KEY (sample_id) REFERENCES samples (sample_id) ON DELETE CASCADE
);

CREATE TABLE ratings (
    rating_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ratings_pkey PRIMARY KEY,
    user_id integer NOT NULL,
    sample_id integer NOT NULL,
    rating integer NOT NULL,
    CONSTRAINT ratings_user_fkey FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT ratings_sample_fkey FOREIGN KEY (sample_id) REFERENCES samples (sample_id) ON DELETE CASCADE,
    CONSTRAINT ratings_user_sample_key UNIQUE (user_id, sample_id),
    CONSTRAINT ratings_value_check CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE downloads (
    download_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT downloads_pkey PRIMARY KEY,
    user_id integer NOT NULL,
    sample_id integer,
    downloaded_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT downloads_user_fkey FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT downloads_sample_fkey FOREIGN KEY (sample_id) REFERENCES samples (sample_id) ON DELETE SET NULL,
    CONSTRAINT downloads_date_check CHECK (isfinite(downloaded_at))
);

CREATE TABLE login_events (
    login_event_id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT login_events_pkey PRIMARY KEY,
    user_id integer NOT NULL,
    logged_in_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT login_events_user_fkey FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT login_events_date_check CHECK (isfinite(logged_in_at))
);

-- Active catalog: prefix name search, BPM and newest uploads.
CREATE INDEX samples_active_name_idx ON samples (lower(name) text_pattern_ops) WHERE NOT is_deleted;
CREATE INDEX samples_active_bpm_idx ON samples (bpm) WHERE NOT is_deleted;
CREATE INDEX samples_active_upload_date_idx ON samples (upload_date DESC) WHERE NOT is_deleted;
-- Ownership lookup, owner/date filtering and foreign-key deletion checks.
CREATE INDEX samples_owner_upload_date_idx ON samples (owner_id, upload_date DESC);
CREATE INDEX collections_owner_idx ON collections (owner_id);
-- Reverse lookups not covered by the leading columns of composite primary keys.
CREATE INDEX sample_tags_tag_sample_idx ON sample_tags (tag_id, sample_id);
CREATE INDEX collection_samples_sample_collection_idx ON collection_samples (sample_id, collection_id);
-- Sample aggregates/deletion and chronological per-user activity.
CREATE INDEX ratings_sample_idx ON ratings (sample_id);
CREATE INDEX downloads_user_date_idx ON downloads (user_id, downloaded_at DESC);
CREATE INDEX downloads_sample_date_idx ON downloads (sample_id, downloaded_at DESC);
CREATE INDEX login_events_user_date_idx ON login_events (user_id, logged_in_at DESC);

COMMIT;
